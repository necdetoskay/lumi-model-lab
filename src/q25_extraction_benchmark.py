"""Q25 zero-cost extractor *calibration* against openly authored story labels.

This module does not run a model or authenticate an independent reviewer.
Manual reference labels are neither a blind test nor a canonical state oracle.
"""
from __future__ import annotations

import argparse
import copy
import json
from pathlib import Path

from src.q25_entity_candidates import fingerprint
from src.q25_extractor_adapter import materialize_quotes, offline_replay

CLAIM_GROUPS = (
    "objects", "terminal_relations", "character_claims", "goal_claims",
    "obligation_claims", "thread_claims", "property_claims",
)


def _identity(group, claim):
    if group == "objects":
        return (claim["key"], claim["role"])
    if group == "terminal_relations":
        return (claim["subject"], claim["kind"], claim["target"])
    if group == "character_claims":
        return (claim["actor"], claim["field"], claim["value"],
                claim["epistemic_type"], claim["other_actor"])
    if group == "goal_claims":
        return (claim["actor"], claim["goal_id"], claim["outcome"])
    if group == "obligation_claims":
        return (claim["obligation_id"], claim["outcome"])
    if group == "thread_claims":
        return (claim["thread_id"], claim["outcome"])
    if group == "property_claims":
        return (claim["object_id"], claim["property_name"],
                type(claim["expected_seed_value"]).__name__,
                repr(claim["expected_seed_value"]),
                type(claim["proposed_terminal_value"]).__name__,
                repr(claim["proposed_terminal_value"]), claim["evidence_kind"])
    raise ValueError("Unknown claim group")


def _claims(materialized):
    """A source-quoted claim may still be semantically unsupported."""
    result = {}
    proposal_for = {
        "objects": ("entity_proposal", "objects"),
        "terminal_relations": ("entity_proposal", "terminal_relations"),
        "character_claims": ("story_proposal", "character_claims"),
        "goal_claims": ("story_proposal", "goal_claims"),
        "obligation_claims": ("story_proposal", "obligation_claims"),
        "thread_claims": ("story_proposal", "thread_claims"),
        "property_claims": ("property_proposal", "claims"),
    }
    for group in CLAIM_GROUPS:
        proposal, name = proposal_for[group]
        for claim in materialized[proposal][name]:
            key = fingerprint({"group": group, "identity": _identity(group, claim)})
            if key in result:
                raise ValueError("Duplicate semantic identity within extractor output")
            source = (claim["mention"] if group == "objects" else claim["evidence"])
            if isinstance(source, dict):
                source = [source]
            result[key] = {
                "group": group,
                "identity": _identity(group, claim),
                "quotes": [s["text"] for s in source],
                "citations": copy.deepcopy(source),
            }
    return result


def _score(gold, candidate):
    correct = set(gold) & set(candidate)
    wrong = set(candidate) - set(gold)
    missing = set(gold) - set(candidate)
    tp, fp, fn = len(correct), len(wrong), len(missing)
    return {
        "true_positive": tp,
        "false_positive": fp,
        "false_negative": fn,
        "precision": (tp / (tp + fp)) if tp + fp else 0.0,
        "recall": (tp / (tp + fn)) if tp + fn else 0.0,
        "f1": (2 * tp / (2 * tp + fp + fn)) if 2 * tp + fp + fn else 0.0,
        "reference_quote_exact_matches": sum(
            set(gold[k]["quotes"]).issubset(set(candidate[k]["quotes"]))
            for k in correct
        ),
    }


def calibrate(*, seed, prose, policy, gold_raw_output, candidate_raw_output):
    """Score a supplied envelope; never pretend it was generated by a provider."""
    originals = copy.deepcopy((
        seed, prose, policy, gold_raw_output, candidate_raw_output,
    ))
    gold_status = offline_replay(
        seed=seed, prose=prose, policy=policy, raw_output=gold_raw_output)
    pred_status = offline_replay(
        seed=seed, prose=prose, policy=policy, raw_output=candidate_raw_output)
    if (gold_status["status"] != "SOURCE_BOUND_CANDIDATES_ONLY"
            or pred_status["status"] != "SOURCE_BOUND_CANDIDATES_ONLY"):
        raise ValueError("Both envelopes must pass the existing candidate gates")
    gold = _claims(materialize_quotes(
        seed=seed, prose=prose, raw_output=gold_raw_output))
    candidate = _claims(materialize_quotes(
        seed=seed, prose=prose, raw_output=candidate_raw_output))
    per_group = {
        group: _score(
            {k: v for k, v in gold.items() if v["group"] == group},
            {k: v for k, v in candidate.items() if v["group"] == group},
        )
        for group in CLAIM_GROUPS
    }
    total = _score(gold, candidate)
    classifications = {
        "matched_reference_claims": [
            candidate[k] for k in sorted(set(candidate) & set(gold))],
        "extra_claims_not_in_reference": [
            candidate[k] for k in sorted(set(candidate) - set(gold))],
        "missed_reference_claims": [
            gold[k] for k in sorted(set(gold) - set(candidate))],
    }
    assert originals == (
        seed, prose, policy, gold_raw_output, candidate_raw_output,
    )
    return {
        "schema": "q25.extraction-calibration-report.v1",
        "seed_sha256": gold_raw_output["seed_sha256"],
        "source_sha256": gold_raw_output["source_sha256"],
        "gold_raw_sha256": fingerprint(gold_raw_output),
        "candidate_raw_sha256": fingerprint(candidate_raw_output),
        "reference_label_origin": "MANUALLY_CURATED_UNVERIFIED",
        "candidate_origin": "SUPPLIED_ENVELOPE_NOT_AUTHENTICATED_AS_MODEL_OUTPUT",
        "evaluation_scope": "OPEN_FIXTURE_CLAIM_IDENTITY_NOT_BLIND_MODEL_EVALUATION",
        "candidate_structural_replay_status": pred_status["status"],
        "reference_structural_replay_status": gold_status["status"],
        "coverage_field_count": pred_status["coverage"]["blocking_field_count"],
        "reference_claim_count": len(gold),
        "candidate_claim_count": len(candidate),
        "overall": total,
        "by_claim_group": per_group,
        **classifications,
        "reference_labels_independently_adjudicated": False,
        "real_model_success_measured": False,
        "false_positive_semantic_support_independently_verified": False,
        "state_commit_authorized": False,
        "full_story_state_qualified": False,
        "semantic_support_certified": False,
        "provider_calls": 0,
        "provider_cost_usd": 0.0,
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--fixture", type=Path, required=True)
    parser.add_argument("--prediction", type=Path)
    args = parser.parse_args()
    fixture = json.loads(args.fixture.read_text(encoding="utf8"))
    if fixture["schema_name"] != "q25.new-story-calibration-fixture.v1":
        raise ValueError("Unknown calibration fixture contract")
    if fixture["blind_holdout"] is not False or (
            fixture["test_story_origin"] !=
            "AUTHORED_OFFLINE_FIXTURE_NOT_MODEL_GENERATED"):
        raise ValueError("This command is solely for open, offline fixtures")
    prediction = (
        json.loads(args.prediction.read_text(encoding="utf8"))
        if args.prediction else fixture["flawed_candidate_raw_output"]
    )
    report = calibrate(
        seed=fixture["seed"], prose=fixture["prose"], policy=fixture["policy"],
        gold_raw_output=fixture["gold_raw_output"],
        candidate_raw_output=prediction,
    )
    print(json.dumps(report, ensure_ascii=False, sort_keys=True, indent=2))


if __name__ == "__main__":
    main()
